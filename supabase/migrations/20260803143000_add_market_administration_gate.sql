create or replace function private.require_current_admin()
returns uuid
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from auth.users u
    where u.id = current_user_id
      and coalesce((u.raw_app_meta_data ->> 'oraklo_admin')::boolean, false) = true
  ) then
    raise exception 'ADMIN_REQUIRED' using errcode = '42501';
  end if;

  return current_user_id;
end;
$function$;

revoke all on function private.require_current_admin() from public, anon, authenticated;

create or replace function private.market_draft_fingerprint(draft private.market_drafts)
returns text
language sql
immutable
set search_path = ''
as $function$
  select md5(concat_ws(
    E'\n',
    coalesce(draft.market_slug, ''), coalesce(draft.question, ''),
    coalesce(draft.subject, ''), coalesce(draft.category, ''),
    coalesce(draft.yes_option, ''), coalesce(draft.no_option, ''),
    coalesce(draft.evaluation_period_label, ''),
    coalesce(extract(epoch from draft.evaluation_ends_at)::text, ''),
    coalesce(draft.timezone, ''),
    coalesce(extract(epoch from draft.resolution_deadline)::text, ''),
    coalesce(draft.yes_criteria, ''), coalesce(draft.no_criteria, ''),
    coalesce(draft.edge_cases, ''), coalesce(draft.primary_source::text, ''),
    coalesce(draft.alternative_sources::text, ''), coalesce(draft.delay_treatment, ''),
    coalesce(draft.cancellation_treatment, ''), coalesce(draft.leak_treatment, ''),
    coalesce(draft.rename_treatment, ''), coalesce(draft.assumptions, ''),
    coalesce(draft.public_criteria, '')
  ));
$function$;

revoke all on function private.market_draft_fingerprint(private.market_drafts)
  from public, anon, authenticated;

create or replace function private.market_draft_deterministic_issues(draft private.market_drafts)
returns jsonb
language plpgsql
stable
set search_path = ''
as $function$
declare
  issues jsonb := '[]'::jsonb;
  primary_url text := trim(coalesce(draft.primary_source ->> 'url', ''));
  alternative jsonb;
begin
  if length(trim(coalesce(draft.question, ''))) < 20 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'QUESTION_REQUIRED', 'field', 'question',
      'message', 'Escribe una pregunta completa y medible de al menos 20 caracteres.'
    ));
  end if;

  if coalesce(draft.question, '') ~* '\m(exito|éxito|importante|grande|pronto|el próximo|el proximo|el último|el ultimo|este evento)\M' then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'QUESTION_AMBIGUOUS_TERM', 'field', 'question',
      'message', 'La pregunta contiene un término relativo o subjetivo que necesita una métrica, fecha o edición concreta.'
    ));
  end if;

  if length(trim(coalesce(draft.subject, ''))) < 3 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'SUBJECT_REQUIRED', 'field', 'subject',
      'message', 'Identifica de forma inequívoca el sujeto, evento o producto.'
    ));
  end if;

  if length(trim(coalesce(draft.category, ''))) < 2 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'CATEGORY_REQUIRED', 'field', 'category',
      'message', 'Selecciona una categoría.'
    ));
  end if;

  if lower(trim(coalesce(draft.yes_option, ''))) = lower(trim(coalesce(draft.no_option, '')))
     or lower(trim(coalesce(draft.yes_option, ''))) not in ('sí', 'si')
     or lower(trim(coalesce(draft.no_option, ''))) <> 'no' then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'OPTIONS_NOT_BINARY', 'field', 'options',
      'message', 'Las opciones deben ser Sí y No, mutuamente excluyentes.'
    ));
  end if;

  if length(trim(coalesce(draft.evaluation_period_label, ''))) < 8
     or draft.evaluation_ends_at is null
     or draft.closes_at is null then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'PERIOD_REQUIRED', 'field', 'evaluation_period',
      'message', 'Define el periodo evaluado y su final exacto.'
    ));
  elsif draft.evaluation_ends_at <> draft.closes_at then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'TEMPORAL_CONTRADICTION', 'field', 'evaluation_ends_at',
      'message', 'El cierre de participación debe derivarse del final del periodo y no contradecirlo.'
    ));
  end if;

  if length(trim(coalesce(draft.timezone, ''))) < 3
     or not exists (
       select 1 from pg_catalog.pg_timezone_names tz where tz.name = draft.timezone
     ) then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'TIMEZONE_INVALID', 'field', 'timezone',
      'message', 'Selecciona una zona horaria IANA válida, por ejemplo Europe/Madrid.'
    ));
  end if;

  if draft.resolution_deadline is null
     or (draft.evaluation_ends_at is not null and draft.resolution_deadline < draft.evaluation_ends_at) then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'RESOLUTION_DEADLINE_INVALID', 'field', 'resolution_deadline',
      'message', 'La fecha límite de resolución debe ser posterior al final del periodo evaluado.'
    ));
  end if;

  if length(trim(coalesce(draft.yes_criteria, ''))) < 20 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'YES_CRITERIA_REQUIRED', 'field', 'yes_criteria',
      'message', 'Describe la prueba exacta que resuelve Sí.'
    ));
  end if;
  if length(trim(coalesce(draft.no_criteria, ''))) < 20 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'NO_CRITERIA_REQUIRED', 'field', 'no_criteria',
      'message', 'Describe la prueba exacta que resuelve No.'
    ));
  end if;
  if lower(trim(coalesce(draft.yes_criteria, ''))) = lower(trim(coalesce(draft.no_criteria, '')))
     and length(trim(coalesce(draft.yes_criteria, ''))) > 0 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'OPTIONS_OVERLAP', 'field', 'no_criteria',
      'message', 'Los criterios de Sí y No se solapan y permitirían dos resoluciones razonables.'
    ));
  end if;

  if length(trim(coalesce(draft.edge_cases, ''))) < 20 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'EDGE_CASES_REQUIRED', 'field', 'edge_cases',
      'message', 'Define los casos límite aplicables.'
    ));
  end if;

  if primary_url !~* '^https://'
     or primary_url ~* '^https://(localhost|127\.|10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.)' then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'PRIMARY_SOURCE_INVALID', 'field', 'primary_source',
      'message', 'Añade una fuente principal pública y verificable con URL HTTPS.'
    ));
  end if;

  if jsonb_array_length(coalesce(draft.alternative_sources, '[]'::jsonb)) < 1 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'ALTERNATIVE_SOURCE_REQUIRED', 'field', 'alternative_sources',
      'message', 'Añade al menos una fuente alternativa pública.'
    ));
  else
    for alternative in select value from jsonb_array_elements(draft.alternative_sources)
    loop
      if trim(coalesce(alternative ->> 'url', '')) !~* '^https://'
         or trim(coalesce(alternative ->> 'url', '')) ~* '^https://(localhost|127\.|10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.)' then
        issues := issues || jsonb_build_array(jsonb_build_object(
          'code', 'ALTERNATIVE_SOURCE_INVALID', 'field', 'alternative_sources',
          'message', 'Todas las fuentes alternativas deben usar una URL HTTPS pública.'
        ));
        exit;
      end if;
    end loop;
  end if;

  if length(trim(coalesce(draft.public_criteria, ''))) < 30 then
    issues := issues || jsonb_build_array(jsonb_build_object(
      'code', 'PUBLIC_CRITERIA_REQUIRED', 'field', 'public_criteria',
      'message', 'Explica públicamente cómo se resolverá el mercado.'
    ));
  end if;

  return issues;
end;
$function$;

revoke all on function private.market_draft_deterministic_issues(private.market_drafts)
  from public, anon, authenticated;

create or replace function public.save_market_draft(
  draft_id_input uuid,
  expected_version_input bigint,
  draft_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  actor_id uuid := private.require_current_admin();
  draft_row private.market_drafts%rowtype;
  previous_fingerprint text;
  next_fingerprint text;
  issues jsonb;
  next_evaluation_end timestamptz;
  next_resolution_deadline timestamptz;
  next_slug text := lower(trim(coalesce(draft_input ->> 'market_slug', '')));
  was_created boolean := draft_id_input is null;
begin
  if jsonb_typeof(draft_input) <> 'object' then
    raise exception 'INVALID_DRAFT_PAYLOAD' using errcode = '22023';
  end if;
  if octet_length(draft_input::text) > 65536 then
    raise exception 'DRAFT_PAYLOAD_TOO_LARGE' using errcode = '22023';
  end if;

  if next_slug !~ '^[a-z0-9][a-z0-9-]{2,119}$' then
    raise exception 'INVALID_MARKET_SLUG' using errcode = '22023';
  end if;

  begin
    next_evaluation_end := nullif(trim(draft_input ->> 'evaluation_ends_at'), '')::timestamptz;
    next_resolution_deadline := nullif(trim(draft_input ->> 'resolution_deadline'), '')::timestamptz;
  exception when invalid_datetime_format then
    raise exception 'INVALID_DRAFT_DATE' using errcode = '22007';
  end;

  if draft_id_input is null then
    insert into private.market_drafts (
      market_slug, question, subject, category, yes_option, no_option,
      evaluation_period_label, evaluation_ends_at, closes_at, timezone,
      resolution_deadline, yes_criteria, no_criteria, edge_cases,
      primary_source, alternative_sources, delay_treatment,
      cancellation_treatment, leak_treatment, rename_treatment, assumptions,
      public_criteria, description, created_by, updated_by
    ) values (
      next_slug, nullif(trim(draft_input ->> 'question'), ''),
      nullif(trim(draft_input ->> 'subject'), ''), nullif(trim(draft_input ->> 'category'), ''),
      coalesce(nullif(trim(draft_input ->> 'yes_option'), ''), 'Sí'),
      coalesce(nullif(trim(draft_input ->> 'no_option'), ''), 'No'),
      nullif(trim(draft_input ->> 'evaluation_period_label'), ''),
      next_evaluation_end, next_evaluation_end, nullif(trim(draft_input ->> 'timezone'), ''),
      next_resolution_deadline, nullif(trim(draft_input ->> 'yes_criteria'), ''),
      nullif(trim(draft_input ->> 'no_criteria'), ''), nullif(trim(draft_input ->> 'edge_cases'), ''),
      coalesce(draft_input -> 'primary_source', '{}'::jsonb),
      coalesce(draft_input -> 'alternative_sources', '[]'::jsonb),
      nullif(trim(draft_input ->> 'delay_treatment'), ''),
      nullif(trim(draft_input ->> 'cancellation_treatment'), ''),
      nullif(trim(draft_input ->> 'leak_treatment'), ''),
      nullif(trim(draft_input ->> 'rename_treatment'), ''),
      nullif(trim(draft_input ->> 'assumptions'), ''),
      nullif(trim(draft_input ->> 'public_criteria'), ''),
      nullif(trim(draft_input ->> 'description'), ''), actor_id, actor_id
    ) returning * into draft_row;
  else
    select * into draft_row
    from private.market_drafts
    where id = draft_id_input
    for update;

    if not found then
      raise exception 'DRAFT_NOT_FOUND' using errcode = 'P0001';
    end if;
    if expected_version_input is null or expected_version_input <> draft_row.content_version then
      raise exception 'DRAFT_VERSION_MOVED' using errcode = '40001';
    end if;
    if draft_row.workflow_status in ('published', 'early_closed', 'cancelled', 'pending_resolution', 'resolved', 'annulled') then
      raise exception 'PUBLISHED_MARKET_FIELDS_LOCKED' using errcode = '22023';
    end if;

    previous_fingerprint := private.market_draft_fingerprint(draft_row);
    update private.market_drafts set
      market_slug = next_slug,
      question = nullif(trim(draft_input ->> 'question'), ''),
      subject = nullif(trim(draft_input ->> 'subject'), ''),
      category = nullif(trim(draft_input ->> 'category'), ''),
      yes_option = coalesce(nullif(trim(draft_input ->> 'yes_option'), ''), 'Sí'),
      no_option = coalesce(nullif(trim(draft_input ->> 'no_option'), ''), 'No'),
      evaluation_period_label = nullif(trim(draft_input ->> 'evaluation_period_label'), ''),
      evaluation_ends_at = next_evaluation_end,
      closes_at = next_evaluation_end,
      timezone = nullif(trim(draft_input ->> 'timezone'), ''),
      resolution_deadline = next_resolution_deadline,
      yes_criteria = nullif(trim(draft_input ->> 'yes_criteria'), ''),
      no_criteria = nullif(trim(draft_input ->> 'no_criteria'), ''),
      edge_cases = nullif(trim(draft_input ->> 'edge_cases'), ''),
      primary_source = coalesce(draft_input -> 'primary_source', '{}'::jsonb),
      alternative_sources = coalesce(draft_input -> 'alternative_sources', '[]'::jsonb),
      delay_treatment = nullif(trim(draft_input ->> 'delay_treatment'), ''),
      cancellation_treatment = nullif(trim(draft_input ->> 'cancellation_treatment'), ''),
      leak_treatment = nullif(trim(draft_input ->> 'leak_treatment'), ''),
      rename_treatment = nullif(trim(draft_input ->> 'rename_treatment'), ''),
      assumptions = nullif(trim(draft_input ->> 'assumptions'), ''),
      public_criteria = nullif(trim(draft_input ->> 'public_criteria'), ''),
      description = nullif(trim(draft_input ->> 'description'), ''),
      content_version = content_version + 1,
      updated_by = actor_id,
      updated_at = now()
    where id = draft_id_input
    returning * into draft_row;
  end if;

  next_fingerprint := private.market_draft_fingerprint(draft_row);
  issues := private.market_draft_deterministic_issues(draft_row);

  update private.market_drafts set
    content_fingerprint = next_fingerprint,
    workflow_status = case when jsonb_array_length(issues) = 0 then 'draft_ready' else 'draft_incomplete' end,
    review_status = case
      when was_created or previous_fingerprint is distinct from next_fingerprint then 'not_requested'
      else review_status
    end,
    reviewed_version = case
      when was_created or previous_fingerprint is distinct from next_fingerprint then null
      else reviewed_version
    end,
    reviewed_fingerprint = case
      when was_created or previous_fingerprint is distinct from next_fingerprint then null
      else reviewed_fingerprint
    end,
    human_confirmed_at = case
      when was_created or previous_fingerprint is distinct from next_fingerprint then null
      else human_confirmed_at
    end,
    human_confirmed_by = case
      when was_created or previous_fingerprint is distinct from next_fingerprint then null
      else human_confirmed_by
    end
  where id = draft_row.id
  returning * into draft_row;

  insert into private.market_admin_audit (
    actor_id, action_code, draft_id, draft_version, detail
  ) values (
    actor_id,
    case when was_created then 'DRAFT_CREATED'
      when previous_fingerprint is distinct from next_fingerprint then 'DRAFT_SAVED_REVIEW_INVALIDATED'
      else 'DRAFT_SAVED' end,
    draft_row.id, draft_row.content_version,
    jsonb_build_object('deterministic_issue_count', jsonb_array_length(issues))
  );

  return jsonb_build_object(
    'draft', to_jsonb(draft_row) - 'created_by' - 'updated_by' - 'human_confirmed_by',
    'deterministic_issues', issues
  );
end;
$function$;

revoke all on function public.save_market_draft(uuid, bigint, jsonb)
  from public, anon, authenticated;
grant execute on function public.save_market_draft(uuid, bigint, jsonb)
  to authenticated;

create or replace function public.list_admin_market_drafts(
  status_filter text default null,
  query_filter text default null,
  limit_count integer default 50,
  offset_count integer default 0
)
returns table (
  id uuid, market_id text, market_slug text, question text, category text,
  workflow_status text, review_status text, content_version bigint,
  scheduled_for timestamptz, updated_at timestamptz,
  participants_count integer, karma_total integer
)
language plpgsql
security definer
set search_path = ''
as $function$
begin
  perform private.require_current_admin();
  return query
  select
    d.id, d.market_id, d.market_slug, d.question, d.category,
    d.workflow_status, d.review_status, d.content_version,
    d.scheduled_for, d.updated_at,
    count(p.id)::integer,
    coalesce(sum(p.karma_risked), 0)::integer
  from private.market_drafts d
  left join public.predictions p on p.market_id = d.market_id
  where (status_filter is null or status_filter = '' or d.workflow_status = status_filter)
    and (
      query_filter is null or query_filter = ''
      or d.question ilike '%' || query_filter || '%'
      or d.market_slug ilike '%' || query_filter || '%'
    )
  group by d.id
  order by d.updated_at desc
  limit least(greatest(limit_count, 1), 100)
  offset greatest(offset_count, 0);
end;
$function$;

revoke all on function public.list_admin_market_drafts(text, text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.list_admin_market_drafts(text, text, integer, integer)
  to authenticated;

create or replace function public.get_admin_market_draft(draft_id_input uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  draft_row private.market_drafts%rowtype;
begin
  perform private.require_current_admin();
  select * into draft_row from private.market_drafts where id = draft_id_input;
  if not found then raise exception 'DRAFT_NOT_FOUND' using errcode = 'P0001'; end if;

  return jsonb_build_object(
