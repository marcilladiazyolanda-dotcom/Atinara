  for draft_row in
    select * from private.market_drafts
    where workflow_status = 'scheduled' and scheduled_for <= now()
    order by scheduled_for for update skip locked
    limit least(greatest(limit_count, 1), 100)
  loop
    begin
      published := published || jsonb_build_array(
