create or replace function public.record_market_draft_review(
  draft_id_input uuid,
  draft_version_input bigint,
  content_fingerprint_input text,
  validator_version_input text,
  result_input text,
  semantic_issues_input jsonb,
  editorial_notes_input jsonb,
  reviewed_by_input uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  draft_row private.market_drafts%rowtype;
  normalized_result text := lower(trim(coalesce(result_input, '')));
  next_workflow text;
begin
  if normalized_result not in (
    'approved', 'rejected', 'inconclusive', 'service_unavailable',
    'quota_exhausted', 'invalid_response'
  ) then raise exception 'INVALID_REVIEW_RESULT' using errcode = '22023'; end if;
  if jsonb_typeof(coalesce(semantic_issues_input, '[]'::jsonb)) <> 'array'
     or jsonb_typeof(coalesce(editorial_notes_input, '[]'::jsonb)) <> 'array' then
    raise exception 'INVALID_REVIEW_REPORT' using errcode = '22023';
  end if;

  select * into draft_row from private.market_drafts
  where id = draft_id_input for update;
  if not found then raise exception 'DRAFT_NOT_FOUND' using errcode = 'P0001'; end if;
  if draft_row.workflow_status <> 'review_in_progress'
     or draft_version_input is null
     or draft_row.content_version <> draft_version_input
     or content_fingerprint_input is null
     or draft_row.content_fingerprint is distinct from content_fingerprint_input then
    raise exception 'REVIEW_VERSION_MOVED' using errcode = '40001';
  end if;
  if normalized_result = 'approved'
     and jsonb_array_length(coalesce(semantic_issues_input, '[]'::jsonb)) > 0 then
    raise exception 'APPROVED_REVIEW_HAS_BLOCKERS' using errcode = '22023';
  end if;

  next_workflow := case normalized_result
    when 'approved' then 'review_approved'
    when 'rejected' then 'review_rejected'
    when 'inconclusive' then 'review_inconclusive'
    else 'review_unavailable'
  end;

  insert into private.market_review_reports (
    draft_id, draft_version, content_fingerprint, validator_version,
    result, semantic_issues, editorial_notes, reviewed_by
  ) values (
    draft_row.id, draft_row.content_version, draft_row.content_fingerprint,
    left(trim(validator_version_input), 100), normalized_result,
    coalesce(semantic_issues_input, '[]'::jsonb),
    coalesce(editorial_notes_input, '[]'::jsonb), reviewed_by_input
  );

  update private.market_drafts set
    workflow_status = next_workflow,
    review_status = normalized_result,
    reviewed_version = case when normalized_result = 'approved' then content_version else null end,
    reviewed_fingerprint = case when normalized_result = 'approved' then content_fingerprint else null end,
    human_confirmed_at = null, human_confirmed_by = null,
    updated_at = now(), updated_by = coalesce(reviewed_by_input, updated_by)
  where id = draft_row.id returning * into draft_row;

  insert into private.market_admin_audit (
    actor_id, action_code, draft_id, draft_version, detail
  ) values (
    reviewed_by_input, 'REVIEW_' || upper(normalized_result), draft_row.id,
    draft_row.content_version,
    jsonb_build_object('blocking_reasons', coalesce(semantic_issues_input, '[]'::jsonb))
  );

  return jsonb_build_object(
    'status', normalized_result,
    'workflow_status', draft_row.workflow_status,
    'draft_version', draft_row.content_version
  );
end;
$function$;

