      draft_row.content_version, jsonb_build_object('blocking_reasons', issues)
    );
    return jsonb_build_object('status', 'rejected', 'blocking_reasons', issues);
  end if;

  update private.market_drafts set
    workflow_status = 'review_in_progress', review_status = 'in_progress',
    updated_at = now(), updated_by = actor_id
