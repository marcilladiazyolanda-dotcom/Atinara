create or replace function private.calculate_lmsr_quote(
  selected_probability_input numeric,
  liquidity_parameter_input numeric,
  karma_amount_input numeric
)
returns table (
  acquired_shares numeric,
  new_selected_probability numeric,
  average_entry_price_percentage numeric
)
language plpgsql
immutable
strict
security invoker
set search_path = ''
as $function$
declare
  growth numeric;
begin
  if selected_probability_input <= 0
     or selected_probability_input >= 1
     or liquidity_parameter_input < 100
     or karma_amount_input <= 0 then
    raise exception 'INVALID_LMSR_INPUT'
      using errcode = '22023';
  end if;

  growth := exp(karma_amount_input / liquidity_parameter_input);
  acquired_shares := liquidity_parameter_input * ln(
    (
      growth - (1 - selected_probability_input)
    ) / selected_probability_input
  );
  -- Evita que el redondeo decimal alcance exactamente 0 o 1 después de muchas
  -- participaciones consecutivas en el mismo lado. El mercado puede acercarse
  -- al extremo, pero nunca crea un contrato matemáticamente imposible de cotizar.
  new_selected_probability := greatest(
    0.00000001::numeric,
    least(
      0.99999999::numeric,
      1 - ((1 - selected_probability_input) / growth)
    )
  );
  average_entry_price_percentage := (
    karma_amount_input / acquired_shares
  ) * 100;

  return next;
end;
$function$;

create or replace function private.get_prediction_reward_rules(
  entry_price_percentage_input numeric
)
returns table (
  difficulty text,
  bonus_rate numeric,
  prestige_if_hit integer,
  prestige_if_miss integer
)
language sql
immutable
strict
security invoker
set search_path = ''
as $function$
  with selected_rule as (
    select case
      when entry_price_percentage_input >= 70 then 'Fácil'
      when entry_price_percentage_input >= 50 then 'Normal'
      when entry_price_percentage_input >= 30 then 'Difícil'
      when entry_price_percentage_input >= 15 then 'Muy difícil'
      else 'Épica'
    end as difficulty
  )
  select
    selected_rule.difficulty,
    case selected_rule.difficulty
      when 'Fácil' then 0::numeric
      when 'Normal' then 0.05::numeric
      when 'Difícil' then 0.10::numeric
      when 'Muy difícil' then 0.20::numeric
      when 'Épica' then 0.35::numeric
    end as bonus_rate,
    case selected_rule.difficulty
      when 'Fácil' then 10
      when 'Normal' then 20
      when 'Difícil' then 35
      when 'Muy difícil' then 60
      when 'Épica' then 100
    end as prestige_if_hit,
    case selected_rule.difficulty
      when 'Fácil' then -4
      when 'Normal' then -6
      when 'Difícil' then -8
      when 'Muy difícil' then -10
      when 'Épica' then -15
    end as prestige_if_miss
  from selected_rule;
$function$;

revoke all on function private.calculate_lmsr_quote(numeric, numeric, numeric)
  from public, anon, authenticated;
revoke all on function private.get_prediction_reward_rules(numeric)
  from public, anon, authenticated;

with prediction_stats as (
  select
    market_id,
    count(*)::numeric as total_predictions,
    count(*) filter (where option_selected = 'Sí')::numeric as yes_predictions
  from public.predictions
  group by market_id
), initial_probability as (
  select
    m.id as market_id,
    case
      when coalesce(ps.total_predictions, 0) = 0 then 0.5::numeric
      else greatest(
        0.01::numeric,
        least(0.99::numeric, ps.yes_predictions / ps.total_predictions)
      )
    end as yes_probability
  from public.markets m
  left join prediction_stats ps on ps.market_id = m.id
)
insert into public.market_maker_state (
  market_id,
  pricing_model,
  liquidity_parameter,
  yes_quantity,
  no_quantity,
  yes_probability,
  no_probability,
  version,
  history_started_at,
  updated_at
)
select
  ip.market_id,
  'lmsr_v1',
  2000::numeric,
  case
    when ip.yes_probability >= 0.5
      then round(2000::numeric * ln(ip.yes_probability / (1 - ip.yes_probability)), 8)
    else 0::numeric
  end,
  case
    when ip.yes_probability < 0.5
      then round(2000::numeric * ln((1 - ip.yes_probability) / ip.yes_probability), 8)
    else 0::numeric
  end,
  round(ip.yes_probability, 10),
  round(1 - ip.yes_probability, 10),
  0,
  now(),
  now()
from initial_probability ip;

insert into public.market_price_history (
  market_id,
  recorded_at,
  yes_probability,
  no_probability,
  market_version,
  source
)
select
  market_id,
  history_started_at,
  yes_probability,
  no_probability,
  version,
  'migration'
from public.market_maker_state;

