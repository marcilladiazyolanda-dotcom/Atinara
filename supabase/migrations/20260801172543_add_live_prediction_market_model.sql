  resolution_sources jsonb,
  resolution_ai_model text,
  resolution_ai_generated_at timestamptz,
  yes_price numeric,
  no_price numeric,
  market_version bigint,
  price_updated_at timestamptz,
  price_history_started_at timestamptz,
  pricing_model text,
  liquidity_parameter numeric
)
language sql
security definer
set search_path = ''
as $function$
  with stats as (
    select
      market_id,
      count(*)::integer as total_predictions,
      count(*) filter (where option_selected = 'Sí')::integer as yes_count,
      count(*) filter (where option_selected = 'No')::integer as no_count,
      coalesce(sum(karma_risked), 0)::integer as total_karma
    from public.predictions
    group by market_id
  )
  select
    m.id,
    m.question,
    m.category,
    case
      when m.status = 'Abierto'
       and m.closes_at is not null
       and m.closes_at <= now()
        then 'Cerrado'
      else m.status
    end as status,
    round(coalesce(mm.yes_probability, 0.5) * 100)::integer as yes_percent,
    100 - round(coalesce(mm.yes_probability, 0.5) * 100)::integer as no_percent,
    m.difficulty,
    coalesce(s.total_karma, 0) as karma_total,
    coalesce(s.total_predictions, 0) as participants_count,
    coalesce(m.comments_count, 0) as comments_count,
    case
      when m.status = 'Resuelto' then 'Resuelto'
      when m.status = 'Cerrado'
        or (
          m.status = 'Abierto'
          and m.closes_at is not null
          and m.closes_at <= now()
        ) then 'Pendiente de resolución'
      else m.close_label
    end as close_label,
    m.closes_at,
    m.description,
    m.resolution_source,
    m.yes_criteria,
    m.no_criteria,
    m.edge_case,
    m.highlighted,
    m.popularity,
    m.created_at,
    coalesce(s.total_predictions, 0) as actual_predictions_count,
    coalesce(s.yes_count, 0) as actual_yes_count,
    coalesce(s.no_count, 0) as actual_no_count,
    m.resolution_result,
    m.resolution_note,
    m.resolved_at,
    coalesce(m.resolution_sources, '[]'::jsonb) as resolution_sources,
    m.resolution_ai_model,
    m.resolution_ai_generated_at,
    round(coalesce(mm.yes_probability, 0.5) * 100, 2) as yes_price,
    round(coalesce(mm.no_probability, 0.5) * 100, 2) as no_price,
    coalesce(mm.version, 0) as market_version,
    coalesce(mm.last_trade_at, mm.history_started_at) as price_updated_at,
    mm.history_started_at as price_history_started_at,
    coalesce(mm.pricing_model, 'lmsr_v1') as pricing_model,
    coalesce(mm.liquidity_parameter, 2000) as liquidity_parameter
  from public.markets m
  left join stats s on s.market_id = m.id
  left join public.market_maker_state mm on mm.market_id = m.id
  where m.status in ('Abierto', 'Cerrado', 'Resuelto')
  order by m.highlighted desc, m.popularity desc, m.created_at desc;
$function$;

