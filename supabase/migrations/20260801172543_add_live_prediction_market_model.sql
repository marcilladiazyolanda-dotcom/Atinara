create function public.place_prediction(
  market_id_input text,
  option_selected_input text,
  karma_risked_input integer,
  quote_version_input bigint,
  max_entry_price_input numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_user_id uuid := auth.uid();
  profile_row public.profiles%rowtype;
  market_row public.markets%rowtype;
  maker_row public.market_maker_state%rowtype;
  new_prediction public.predictions%rowtype;
  quote_row record;
  reward_row record;
  selected_probability numeric;
  yes_probability_after numeric;
  no_probability_after numeric;
  base_return numeric;
  base_benefit numeric;
  difficulty_bonus numeric;
  max_allowed_karma integer;
  executed_version bigint;
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED'
      using errcode = '28000';
  end if;

  if option_selected_input is null
     or option_selected_input not in ('Sí', 'No') then
    raise exception 'INVALID_OPTION'
      using errcode = '22023';
  end if;

  if karma_risked_input is null or karma_risked_input < 10 then
    raise exception 'MIN_KARMA_REQUIRED'
      using errcode = '22023';
  end if;

  if quote_version_input is null
     or max_entry_price_input is null
     or max_entry_price_input <= 0
     or max_entry_price_input > 100 then
    raise exception 'INVALID_QUOTE'
      using errcode = '22023';
  end if;

  select *
  into market_row
  from public.markets
  where id = market_id_input
  for update;

  if not found then
    raise exception 'MARKET_NOT_FOUND'
      using errcode = 'P0001';
  end if;

  if market_row.status <> 'Abierto'
     or (market_row.closes_at is not null and market_row.closes_at <= now()) then
    raise exception 'MARKET_NOT_OPEN'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from public.predictions
    where user_id = current_user_id
      and market_id = market_id_input
  ) then
    raise exception 'PREDICTION_ALREADY_EXISTS'
      using errcode = '23505';
  end if;

  select *
  into maker_row
  from public.market_maker_state
  where market_id = market_id_input
  for update;

  if not found then
    raise exception 'MARKET_PRICE_UNAVAILABLE'
      using errcode = 'P0001';
  end if;

  if maker_row.version <> quote_version_input then
    raise exception 'PRICE_MOVED'
      using errcode = '40001';
  end if;

  select *
  into profile_row
  from public.profiles
  where id = current_user_id
  for update;

  if not found then
    raise exception 'PROFILE_NOT_FOUND'
      using errcode = 'P0001';
  end if;

  max_allowed_karma := least(
    floor(profile_row.karma * 0.2)::integer,
    500
  );

  if karma_risked_input > max_allowed_karma then
    raise exception 'MAX_KARMA_EXCEEDED'
      using errcode = '22023';
  end if;

  if profile_row.karma < karma_risked_input then
    raise exception 'INSUFFICIENT_KARMA'
      using errcode = '22023';
  end if;

  selected_probability := case
    when option_selected_input = 'Sí' then maker_row.yes_probability
    else maker_row.no_probability
  end;

  select *
  into quote_row
  from private.calculate_lmsr_quote(
    selected_probability,
    maker_row.liquidity_parameter,
    karma_risked_input::numeric
  );

  if quote_row.average_entry_price_percentage > max_entry_price_input + 0.005 then
    raise exception 'PRICE_MOVED'
      using errcode = '40001';
  end if;

  select *
  into reward_row
  from private.get_prediction_reward_rules(
    quote_row.average_entry_price_percentage
  );

  yes_probability_after := case
    when option_selected_input = 'Sí' then quote_row.new_selected_probability
    else 1 - quote_row.new_selected_probability
  end;
  no_probability_after := 1 - yes_probability_after;
  base_return := quote_row.acquired_shares;
  base_benefit := greatest(base_return - karma_risked_input, 0);
  difficulty_bonus := karma_risked_input::numeric * reward_row.bonus_rate;
  executed_version := maker_row.version + 1;

  insert into public.predictions (
    user_id,
    market_id,
    option_selected,
    entry_percentage,
    option_difficulty,
    karma_risked,
    base_benefit_estimated,
    difficulty_bonus_estimated,
    prestige_if_hit,
    prestige_if_miss,
    status,
    pricing_model,
    contract_shares,
    base_return_estimated,
    entry_price_percentage,
    market_price_before_percentage,
    market_price_after_percentage,
    market_version_before,
    market_version_after
  )
  values (
    current_user_id,
    market_id_input,
    option_selected_input,
    round(quote_row.average_entry_price_percentage)::integer,
    reward_row.difficulty,
    karma_risked_input,
    round(base_benefit, 2),
    round(difficulty_bonus, 2),
    reward_row.prestige_if_hit,
    reward_row.prestige_if_miss,
    'Activa',
    'lmsr_v1',
    round(quote_row.acquired_shares, 8),
    round(base_return, 2),
    round(quote_row.average_entry_price_percentage, 4),
    round(selected_probability * 100, 4),
    round(quote_row.new_selected_probability * 100, 4),
    maker_row.version,
    executed_version
  )
  returning * into new_prediction;

  update public.market_maker_state
  set
    yes_quantity = yes_quantity + case
      when option_selected_input = 'Sí' then quote_row.acquired_shares
      else 0
    end,
    no_quantity = no_quantity + case
      when option_selected_input = 'No' then quote_row.acquired_shares
      else 0
    end,
    yes_probability = round(yes_probability_after, 10),
    no_probability = round(no_probability_after, 10),
    version = executed_version,
    last_trade_at = now(),
    updated_at = now()
  where market_id = market_id_input
  returning * into maker_row;

  insert into public.market_price_history (
    market_id,
    recorded_at,
    yes_probability,
    no_probability,
    market_version,
    source
  )
  values (
    market_id_input,
    maker_row.last_trade_at,
    maker_row.yes_probability,
    maker_row.no_probability,
    maker_row.version,
    'prediction'
  );

  update public.markets
  set
    yes_percent = round(maker_row.yes_probability * 100)::integer,
    no_percent = 100 - round(maker_row.yes_probability * 100)::integer,
    karma_total = (
      select coalesce(sum(p.karma_risked), 0)::integer
      from public.predictions p
      where p.market_id = market_id_input
    ),
    participants_count = (
      select count(*)::integer
      from public.predictions p
      where p.market_id = market_id_input
    )
  where id = market_id_input;

  update public.profiles
  set
    karma = karma - karma_risked_input,
    updated_at = now()
  where id = current_user_id
  returning * into profile_row;

  begin
    perform realtime.send(
      jsonb_build_object(
        'market_id', market_id_input,
        'yes_price_percentage', round(maker_row.yes_probability * 100, 4),
        'no_price_percentage', round(maker_row.no_probability * 100, 4),
        'market_version', maker_row.version,
        'recorded_at', maker_row.last_trade_at
      ),
      'price_changed',
      'market:' || market_id_input,
      false
    );
  exception
    when others then
      raise warning 'MARKET_PRICE_BROADCAST_FAILED:%', sqlstate;
  end;

  return jsonb_build_object(
    'prediction', to_jsonb(new_prediction),
    'profile', jsonb_build_object(
      'id', profile_row.id,
      'username', profile_row.username,
      'karma', profile_row.karma,
      'prestige', profile_row.prestige,
      'rank', profile_row.rank,
      'best_category', profile_row.best_category
    ),
    'market_price', jsonb_build_object(
      'yes_price_percentage', round(maker_row.yes_probability * 100, 4),
      'no_price_percentage', round(maker_row.no_probability * 100, 4),
      'market_version', maker_row.version,
      'recorded_at', maker_row.last_trade_at
    )
  );
end;
$function$;

