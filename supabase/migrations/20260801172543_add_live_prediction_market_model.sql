create or replace function public.get_prediction_quote(
  market_id_input text,
  option_selected_input text,
  karma_risked_input integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  current_user_id uuid := auth.uid();
  market_row public.markets%rowtype;
  maker_row public.market_maker_state%rowtype;
  profile_row public.profiles%rowtype;
  quote_row record;
  reward_row record;
  selected_probability numeric;
  yes_probability_after numeric;
  no_probability_after numeric;
  max_allowed_karma integer := 500;
  base_return numeric;
  base_benefit numeric;
  difficulty_bonus numeric;
begin
  if option_selected_input is null
     or option_selected_input not in ('Sí', 'No') then
    raise exception 'INVALID_OPTION'
      using errcode = '22023';
  end if;

  if karma_risked_input is null or karma_risked_input < 10 then
    raise exception 'MIN_KARMA_REQUIRED'
      using errcode = '22023';
  end if;

  if karma_risked_input > 500 then
    raise exception 'MAX_KARMA_EXCEEDED'
      using errcode = '22023';
  end if;

  select *
  into market_row
  from public.markets
  where id = market_id_input;

  if not found then
    raise exception 'MARKET_NOT_FOUND'
      using errcode = 'P0001';
  end if;

  if market_row.status <> 'Abierto'
     or (market_row.closes_at is not null and market_row.closes_at <= now()) then
    raise exception 'MARKET_NOT_OPEN'
      using errcode = '22023';
  end if;

  select *
  into maker_row
  from public.market_maker_state
  where market_id = market_id_input;

  if not found then
    raise exception 'MARKET_PRICE_UNAVAILABLE'
      using errcode = 'P0001';
  end if;

  if current_user_id is not null then
    if exists (
      select 1
      from public.predictions p
      where p.user_id = current_user_id
        and p.market_id = market_id_input
    ) then
      raise exception 'PREDICTION_ALREADY_EXISTS'
        using errcode = '23505';
    end if;

    select *
    into profile_row
    from public.profiles
    where id = current_user_id;

    if not found then
      raise exception 'PROFILE_NOT_FOUND'
        using errcode = 'P0001';
    end if;

    max_allowed_karma := least(
      floor(profile_row.karma * 0.2)::integer,
      500
    );

    if karma_risked_input > max_allowed_karma then
      raise exception 'MAX_KARMA_EXCEEDED'
        using errcode = '22023';
    end if;
  end if;

  selected_probability := case
    when option_selected_input = 'Sí' then maker_row.yes_probability
    else maker_row.no_probability
  end;

  select *
  into quote_row
  from private.calculate_lmsr_quote(
    selected_probability,
    maker_row.liquidity_parameter,
    karma_risked_input::numeric
  );

  select *
  into reward_row
  from private.get_prediction_reward_rules(
    quote_row.average_entry_price_percentage
  );

  yes_probability_after := case
    when option_selected_input = 'Sí' then quote_row.new_selected_probability
    else 1 - quote_row.new_selected_probability
  end;
  no_probability_after := 1 - yes_probability_after;
  base_return := quote_row.acquired_shares;
  base_benefit := greatest(base_return - karma_risked_input, 0);
  difficulty_bonus := karma_risked_input::numeric * reward_row.bonus_rate;

  return jsonb_build_object(
    'market_id', market_id_input,
    'pricing_model', maker_row.pricing_model,
    'market_version', maker_row.version,
    'option_selected', option_selected_input,
    'karma_risked', karma_risked_input,
    'max_karma_allowed', max_allowed_karma,
    'current_price_percentage', round(selected_probability * 100, 4),
    'average_entry_price_percentage', round(quote_row.average_entry_price_percentage, 4),
    'post_trade_price_percentage', round(quote_row.new_selected_probability * 100, 4),
    'yes_price_after_percentage', round(yes_probability_after * 100, 4),
    'no_price_after_percentage', round(no_probability_after * 100, 4),
    'price_impact_points', round(
      (quote_row.new_selected_probability - selected_probability) * 100,
      4
    ),
    'contract_shares', round(quote_row.acquired_shares, 8),
    'base_return_estimated', round(base_return, 2),
    'base_benefit_estimated', round(base_benefit, 2),
    'option_difficulty', reward_row.difficulty,
    'difficulty_bonus_estimated', round(difficulty_bonus, 2),
    'total_return_estimated', round(base_return + difficulty_bonus, 2),
    'prestige_if_hit', reward_row.prestige_if_hit,
    'prestige_if_miss', reward_row.prestige_if_miss,
    'quoted_at', now()
  );
end;
$function$;

revoke all on function public.get_prediction_quote(text, text, integer)
