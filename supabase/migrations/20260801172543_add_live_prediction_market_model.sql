create or replace function public.resolve_market(
  market_id_input text,
  result_input text,
  resolution_note_input text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  market_row public.markets%rowtype;
  prediction_row public.predictions%rowtype;
  profile_row public.profiles%rowtype;
  normalized_result text;
  correct_prediction boolean;
  karma_credit integer;
  proposed_prestige_change integer;
  applied_prestige_change integer;
  new_prestige integer;
  settled_count integer := 0;
  winners_count integer := 0;
  losers_count integer := 0;
  annulled_count integer := 0;
  total_karma_awarded bigint := 0;
begin
  normalized_result := case lower(trim(coalesce(result_input, '')))
    when 'sí' then 'Sí'
    when 'si' then 'Sí'
    when 'yes' then 'Sí'
    when 'no' then 'No'
    when 'anulado' then 'Anulado'
    when 'anulada' then 'Anulado'
    when 'void' then 'Anulado'
    else null
  end;

  if normalized_result is null then
    raise exception 'INVALID_RESOLUTION_RESULT'
      using errcode = '22023';
  end if;

  select *
  into market_row
  from public.markets
  where id = market_id_input
  for update;

  if not found then
    raise exception 'MARKET_NOT_FOUND'
      using errcode = 'P0001';
  end if;

  if market_row.status = 'Resuelto'
     or market_row.resolution_result is not null then
    raise exception 'MARKET_ALREADY_RESOLVED'
      using errcode = '22023';
  end if;

  if normalized_result <> 'Anulado'
     and market_row.status <> 'Cerrado'
     and (market_row.closes_at is null or market_row.closes_at > now()) then
    raise exception 'MARKET_NOT_CLOSED'
      using errcode = '22023';
  end if;

  update public.markets
  set
    status = 'Resuelto',
    close_label = 'Resuelto',
    resolution_result = normalized_result,
    resolution_note = nullif(trim(resolution_note_input), ''),
    resolved_at = now()
  where id = market_id_input;

  for prediction_row in
    select *
    from public.predictions
    where market_id = market_id_input
      and status = 'Activa'
    order by created_at, id
    for update
  loop
    select *
    into profile_row
    from public.profiles
    where id = prediction_row.user_id
    for update;

    if not found then
      raise exception 'PROFILE_NOT_FOUND_FOR_PREDICTION:%', prediction_row.id
        using errcode = 'P0001';
    end if;

    if normalized_result = 'Anulado' then
      correct_prediction := null;
      karma_credit := prediction_row.karma_risked;
      proposed_prestige_change := 0;
      annulled_count := annulled_count + 1;
    elsif prediction_row.option_selected = normalized_result then
      correct_prediction := true;
      if coalesce(prediction_row.pricing_model, 'legacy_fixed_v1') = 'lmsr_v1' then
        karma_credit := greatest(
          round(
            coalesce(
              prediction_row.contract_shares,
              prediction_row.base_return_estimated,
              0
            ) + coalesce(prediction_row.difficulty_bonus_estimated, 0)
          )::integer,
          0
        );
      else
        -- Las posiciones anteriores conservan exactamente el contrato x10
        -- que estaba vigente cuando se confirmaron.
        karma_credit := least(
          round(
            prediction_row.karma_risked::numeric
              + prediction_row.base_benefit_estimated
              + prediction_row.difficulty_bonus_estimated
          )::integer,
          prediction_row.karma_risked * 10
        );
      end if;
      proposed_prestige_change := prediction_row.prestige_if_hit;
      winners_count := winners_count + 1;
    else
      correct_prediction := false;
      karma_credit := 0;
      proposed_prestige_change := prediction_row.prestige_if_miss;
      losers_count := losers_count + 1;
    end if;

    new_prestige := greatest(
      0,
      profile_row.prestige + proposed_prestige_change
    );
    applied_prestige_change := new_prestige - profile_row.prestige;

    update public.profiles
    set
      karma = karma + karma_credit,
      prestige = new_prestige,
      updated_at = now()
    where id = profile_row.id;

    update public.predictions
    set
      status = case
        when normalized_result = 'Anulado' then 'Anulada'
        when correct_prediction then 'Acertada'
        else 'Fallada'
      end,
      resolution_result = normalized_result,
      is_correct = correct_prediction,
      karma_awarded = karma_credit,
      prestige_change = applied_prestige_change,
      settled_at = now()
    where id = prediction_row.id;

    settled_count := settled_count + 1;
    total_karma_awarded := total_karma_awarded + karma_credit;
  end loop;

  return jsonb_build_object(
    'market_id', market_id_input,
    'result', normalized_result,
    'settled_predictions', settled_count,
    'winners', winners_count,
    'losers', losers_count,
    'annulled', annulled_count,
    'total_karma_awarded', total_karma_awarded,
    'resolved_at', now()
  );
end;
$function$;

