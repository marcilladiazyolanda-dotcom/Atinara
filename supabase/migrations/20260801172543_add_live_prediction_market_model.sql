-- Paso 13.3 · Mercado predictivo vivo con Karma (beta sin compraventa).
--
-- Sustituye los porcentajes calculados por recuento de personas por un creador
-- automático de mercado LMSR. Cada nueva participación compra contratos cuyo
-- precio medio determina el retorno base; el bonus de dificultad se conserva
-- separado y deja de estar limitado por el antiguo tope x10.
--
-- Las predicciones existentes mantienen pricing_model = legacy_fixed_v1 y se
-- liquidan con las condiciones que ya fueron confirmadas. No se reconstruye un
-- histórico artificial: cada mercado empieza a registrar puntos al aplicar
-- esta migración.

begin;

set local lock_timeout = '5s';
set local statement_timeout = '60s';

create table public.market_maker_state (
  market_id text primary key references public.markets(id) on delete cascade,
  pricing_model text not null default 'lmsr_v1'
    check (pricing_model = 'lmsr_v1'),
  liquidity_parameter numeric(20, 8) not null default 2000
    check (liquidity_parameter >= 100),
  yes_quantity numeric(20, 8) not null default 0
    check (yes_quantity >= 0),
  no_quantity numeric(20, 8) not null default 0
    check (no_quantity >= 0),
  yes_probability numeric(12, 10) not null
    check (yes_probability > 0 and yes_probability < 1),
  no_probability numeric(12, 10) not null
    check (no_probability > 0 and no_probability < 1),
  version bigint not null default 0
    check (version >= 0),
  history_started_at timestamptz not null default now(),
  last_trade_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint market_maker_probabilities_sum_check
    check (abs((yes_probability + no_probability) - 1) < 0.00000001)
);

comment on table public.market_maker_state is
  'Estado privado del creador automatico de mercado LMSR de Atinara.';
comment on column public.market_maker_state.liquidity_parameter is
  'Parametro b del LMSR. En beta empieza en 2000 Karma por mercado.';

alter table public.market_maker_state enable row level security;
revoke all on table public.market_maker_state from public, anon, authenticated;

create table public.market_price_history (
  id bigint generated by default as identity primary key,
  market_id text not null references public.markets(id) on delete cascade,
  recorded_at timestamptz not null default now(),
  yes_probability numeric(12, 10) not null
    check (yes_probability > 0 and yes_probability < 1),
  no_probability numeric(12, 10) not null
    check (no_probability > 0 and no_probability < 1),
  market_version bigint not null
    check (market_version >= 0),
  source text not null
    check (source in ('migration', 'initial', 'prediction')),
  constraint market_price_history_probabilities_sum_check
    check (abs((yes_probability + no_probability) - 1) < 0.00000001),
  constraint market_price_history_market_version_key
    unique (market_id, market_version)
);

comment on table public.market_price_history is
  'Puntos reales de precio para la grafica publica. No contiene identidad ni posiciones.';

create index market_price_history_market_recorded_idx
  on public.market_price_history (market_id, recorded_at desc);

alter table public.market_price_history enable row level security;
revoke all on table public.market_price_history from public, anon, authenticated;

