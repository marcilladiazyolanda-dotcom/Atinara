create or replace function public.get_public_market_price_history(
  market_id_input text,
  range_input text default '24h'
)
returns table (
  recorded_at timestamptz,
  yes_percent numeric,
  no_percent numeric,
  market_version bigint
)
language plpgsql
security definer
set search_path = ''
as $function$
declare
  start_at timestamptz;
begin
  if not exists (
    select 1
    from public.markets m
    where m.id = market_id_input
      and m.status in ('Abierto', 'Cerrado', 'Resuelto')
  ) then
    raise exception 'MARKET_NOT_FOUND'
      using errcode = 'P0001';
  end if;

  start_at := case lower(trim(coalesce(range_input, '24h')))
    when '1h' then now() - interval '1 hour'
    when '6h' then now() - interval '6 hours'
    when '24h' then now() - interval '24 hours'
    when '7d' then now() - interval '7 days'
    when 'all' then null
    else null
  end;

  if lower(trim(coalesce(range_input, '24h'))) not in ('1h', '6h', '24h', '7d', 'all') then
    raise exception 'INVALID_HISTORY_RANGE'
      using errcode = '22023';
  end if;

  return query
  with anchor as (
    select h.*
    from public.market_price_history h
    where h.market_id = market_id_input
      and start_at is not null
      and h.recorded_at < start_at
    order by h.recorded_at desc
    limit 1
  ), range_points as (
    select h.*
    from public.market_price_history h
    where h.market_id = market_id_input
      and (start_at is null or h.recorded_at >= start_at)
  ), combined as (
    select * from anchor
    union all
    select * from range_points
  ), limited as (
    select *
    from combined
    order by recorded_at desc
    limit 1200
  )
  select
    limited.recorded_at,
    round(limited.yes_probability * 100, 2) as yes_percent,
    round(limited.no_probability * 100, 2) as no_percent,
    limited.market_version
  from limited
  order by limited.recorded_at asc;
end;
$function$;

