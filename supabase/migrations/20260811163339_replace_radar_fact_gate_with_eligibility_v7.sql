create or replace function public.get_market_intelligence_origin(
  origin_type_input text,
  origin_id_input text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  result jsonb;
  candidate private.external_market_candidates%rowtype;
  eligibility private.market_radar_eligibility_checks%rowtype;
  can_prepare boolean := false;
  blocked_code text;
begin
  if auth.role() <> 'service_role' then
    perform private.require_current_admin();
  end if;

  if origin_type_input = 'observatory_signal' then
    select to_jsonb(signal) || jsonb_build_object(
      'watch_entity_id', (
        select entity.id
        from private.data_observatory_entities entity
        where entity.provider = signal.provider
          and entity.external_id = signal.entity_id
          and entity.active
        order by entity.updated_at desc
        limit 1
      ),
      'recent_context', coalesce((
        select jsonb_agg(to_jsonb(context_row) order by context_row.observed_at desc)
        from (
          select * from private.data_observatory_context_items
          where origin_type = 'observatory_signal'
            and origin_id = origin_id_input
            and active
          order by observed_at desc
          limit 10
        ) context_row
      ), '[]'::jsonb)
    ) into result
    from private.data_observatory_signals signal
    where signal.id::text = origin_id_input;
  elsif origin_type_input = 'radar_candidate' then
    select * into candidate
    from private.external_market_candidates candidate_alias
    where candidate_alias.id::text = origin_id_input;
    if candidate.id is not null then
      select * into eligibility
      from private.market_radar_eligibility_checks check_alias
      where check_alias.id = candidate.current_eligibility_check_id;
      can_prepare := (candidate.state in ('available', 'prepared')
        and candidate.verification_status = 'verified_open'
        and candidate.eligibility_status = 'eligible'
        and candidate.eligibility_policy_version = 'atinara-prediction-policy-v5'
        and eligibility.id is not null
        and eligibility.candidate_id = candidate.id
        and eligibility.status = 'eligible'
        and eligibility.policy_version = 'atinara-prediction-policy-v5'
        and eligibility.expires_at > now()
        and private.market_radar_candidate_resolution_source_ready_v1(candidate));
      blocked_code := case
        when can_prepare then null
        when candidate.eligibility_status = 'terminal'
          or candidate.verification_status = 'rejected_resolved'
          then 'EVENT_ALREADY_RESOLVED'
        when candidate.eligibility_status = 'duplicate'
          or candidate.verification_status = 'rejected_duplicate'
          then 'DUPLICATE_MARKET'
        when candidate.eligibility_policy_version is distinct from 'atinara-prediction-policy-v5'
          then 'RADAR_ELIGIBILITY_POLICY_OUTDATED'
        when candidate.eligibility_status = 'eligible'
          and not private.market_radar_candidate_resolution_source_ready_v1(candidate)
          then 'RADAR_RESOLUTION_SOURCE_REQUIRED'
        when candidate.state not in ('available', 'prepared')
          then 'RADAR_CANDIDATE_NOT_PREPARABLE'
        else 'RADAR_ELIGIBILITY_REQUIRED'
      end;
      result := private.market_radar_eligibility_payload(candidate) || jsonb_build_object(
        'advancement_gate', jsonb_build_object(
          'can_analyze', true,
          'can_prepare', can_prepare,
          'blocked_code', blocked_code,
          'retryable', blocked_code in ('RADAR_ELIGIBILITY_REQUIRED', 'RADAR_RESOLUTION_SOURCE_REQUIRED'),
          'eligibility_check_id', eligibility.id,
          'eligibility_status', eligibility.status
        )
      );
    end if;
  elsif origin_type_input = 'context_story_arc' then
    select to_jsonb(arc) into result
    from private.data_observatory_story_arcs arc
    where arc.id::text = origin_id_input;
  else
    raise exception 'INTELLIGENCE_ORIGIN_INVALID' using errcode = '22023';
  end if;
  if result is null then
    raise exception 'INTELLIGENCE_ORIGIN_NOT_FOUND' using errcode = 'P0001';
  end if;
  return result;
end;
