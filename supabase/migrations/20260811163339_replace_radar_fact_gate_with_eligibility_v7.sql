create or replace function public.apply_market_radar_prepare_eligibility_v1(
  candidate_id_input uuid,
  expected_preparation_revision_input bigint,
  normalizer_version_input text,
  eligibility_checked_at_input timestamptz,
  eligibility_input jsonb,
  eligibility_check_input jsonb,
  reserve_for_prepare_input boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  candidate private.external_market_candidates%rowtype;
  check_row private.market_radar_eligibility_checks%rowtype;
  check_attempt_id uuid;
  check_expires_at timestamptz;
  check_status text;
  safe_payload jsonb;
begin
  if auth.role() <> 'service_role' then
    raise exception 'SERVICE_ROLE_REQUIRED' using errcode = '42501';
  end if;
  if normalizer_version_input <> 'atinara-radar-v2'
     or jsonb_typeof(eligibility_input) <> 'object'
     or jsonb_typeof(eligibility_check_input) <> 'object'
     or eligibility_input ->> 'eligibility_policy_version' is distinct from 'atinara-prediction-policy-v5'
     or eligibility_check_input ->> 'policy_version' is distinct from 'atinara-prediction-policy-v5'
     or eligibility_input ->> 'eligibility_status' is distinct from eligibility_check_input ->> 'status'
     or coalesce(eligibility_check_input ->> 'decision_hash', '') !~ '^[0-9a-f]{64}$' then
    raise exception 'INVALID_RADAR_ELIGIBILITY' using errcode = '22023';
  end if;
  begin
    check_attempt_id := (eligibility_check_input ->> 'attempt_id')::uuid;
    check_expires_at := (eligibility_check_input ->> 'expires_at')::timestamptz;
  exception when invalid_text_representation or datetime_field_overflow then
    raise exception 'INVALID_RADAR_ELIGIBILITY_DATE' using errcode = '22007';
  end;
  check_status := eligibility_check_input ->> 'status';
  if check_status not in ('eligible', 'terminal', 'inactive_option', 'technical_hold', 'invalid', 'duplicate')
     or check_expires_at <= eligibility_checked_at_input
     or jsonb_typeof(coalesce(eligibility_check_input -> 'evidence', '[]'::jsonb)) <> 'array'
     or jsonb_array_length(coalesce(eligibility_check_input -> 'evidence', '[]'::jsonb)) > 12 then
    raise exception 'INVALID_RADAR_ELIGIBILITY' using errcode = '22023';
  end if;

  select * into candidate
  from private.external_market_candidates candidate_alias
  where candidate_alias.id = candidate_id_input
  for update;
  if not found then raise exception 'RADAR_CANDIDATE_NOT_FOUND' using errcode = 'P0001'; end if;
  if candidate.preparation_revision is distinct from expected_preparation_revision_input then
    raise exception 'PREPARATION_REVISION_MISMATCH' using errcode = '40001';
  end if;
  if eligibility_input ->> 'provider' is distinct from candidate.provider
     or eligibility_input ->> 'external_id' is distinct from candidate.external_id
     or eligibility_check_input ->> 'provider' is distinct from candidate.provider
     or eligibility_check_input ->> 'external_id' is distinct from candidate.external_id then
    raise exception 'RADAR_ELIGIBILITY_IDENTITY_MISMATCH' using errcode = '40001';
  end if;

  -- Una resolución terminal ya vinculada es monotónica también frente a una
  -- comprobación concurrente iniciada cuando la candidata aún parecía abierta.
  -- Solo una reparación administrativa auditada (fuera de esta RPC) podría
  -- reconsiderarla; ni un reintento ni el estado abierto del proveedor lo hacen.
  if candidate.eligibility_status = 'terminal' and check_status <> 'terminal' then
    check_status := 'terminal';
    eligibility_input := eligibility_input || jsonb_build_object(
      'eligibility_status', 'terminal',
      'eligibility_reason_code', candidate.eligibility_reason_code,
      'eligibility_reason', candidate.eligibility_reason,
      'eligibility_evidence', candidate.eligibility_evidence,
      'eligibility_policy_version', 'atinara-prediction-policy-v5'
    );
    eligibility_check_input := eligibility_check_input || jsonb_build_object(
      'status', 'terminal',
      'reason_code', candidate.eligibility_reason_code,
      'reason', candidate.eligibility_reason,
      'evidence', candidate.eligibility_evidence,
      'decision_hash', encode(extensions.digest(convert_to(
        concat_ws('|', candidate.provider, candidate.external_id, 'terminal',
          coalesce(candidate.eligibility_reason_code, ''), eligibility_checked_at_input::text),
        'UTF8'
      ), 'sha256'), 'hex')
    );
  end if;

  -- A retry with the same attempt is a read of the current authoritative
  -- outcome, never a second material write. The candidate row is already
  -- locked, so concurrent double-clicks serialize here after the first
  -- transaction commits. Apply the terminal-monotonic transform first so an
  -- originally-open request replays against the exact persisted terminal hash.
  select * into check_row
  from private.market_radar_eligibility_checks check_alias
  where check_alias.attempt_id = check_attempt_id;
  if found then
    if check_row.candidate_id is distinct from candidate.id
       or check_row.decision_hash is distinct from lower(eligibility_check_input ->> 'decision_hash') then
      raise exception 'RADAR_ELIGIBILITY_IDEMPOTENCY_CONFLICT' using errcode = '40001';
    end if;
    safe_payload := private.market_radar_eligibility_payload(candidate);
    if candidate.eligibility_status <> 'eligible' then
      return jsonb_build_object(
        'ok', false,
        'error', case when candidate.eligibility_status = 'terminal'
          then 'RADAR_CANDIDATE_RESOLVED'
          when candidate.eligibility_status = 'duplicate'
          then 'RADAR_CONFIRMED_DUPLICATE'
          else coalesce(candidate.eligibility_reason_code, 'RADAR_CANDIDATE_INELIGIBLE') end,
        'candidate', safe_payload,
        'persisted', true,
        'idempotent', true,
        'reservation', jsonb_build_object('preparation_revision', candidate.preparation_revision)
      );
    end if;
    if reserve_for_prepare_input and candidate.state <> 'available' then
      raise exception 'CANDIDATE_NOT_PREPARABLE' using errcode = '40001';
    end if;
    return jsonb_build_object(
      'ok', true,
      'candidate', safe_payload,
      'eligibility_check_id', candidate.current_eligibility_check_id,
      'idempotent', true,
      'reservation', jsonb_build_object(
        'preparation_revision', candidate.preparation_revision,
        'idempotent', true
      )
    );
  end if;

  insert into private.market_radar_eligibility_checks (
    attempt_id, candidate_id, provider, external_id, event_group_key,
    policy_version, status, reason_code, reason, evidence,
    checked_at, expires_at, decision_hash
  ) values (
    check_attempt_id,
    candidate.id,
    candidate.provider,
    candidate.external_id,
    candidate.event_group_key,
    'atinara-prediction-policy-v5',
    check_status,
    nullif(left(eligibility_check_input ->> 'reason_code', 100), ''),
    nullif(left(eligibility_check_input ->> 'reason', 1000), ''),
    coalesce(eligibility_check_input -> 'evidence', '[]'::jsonb),
    eligibility_checked_at_input,
    check_expires_at,
    lower(eligibility_check_input ->> 'decision_hash')
  ) on conflict (attempt_id) do nothing;

  select * into check_row
  from private.market_radar_eligibility_checks check_alias
  where check_alias.attempt_id = check_attempt_id;
  if not found
     or check_row.candidate_id is distinct from candidate.id
     or check_row.decision_hash is distinct from lower(eligibility_check_input ->> 'decision_hash') then
    raise exception 'RADAR_ELIGIBILITY_IDEMPOTENCY_CONFLICT' using errcode = '40001';
  end if;

  update private.external_market_candidates candidate_alias set
    normalized_payload = (
      candidate_alias.normalized_payload
      - 'atinara_resolution_source_url'
      - 'resolution_source_evidence'
    ) || jsonb_strip_nulls(jsonb_build_object(
      'atinara_question', eligibility_input ->> 'atinara_question',
      'atinara_category', eligibility_input ->> 'atinara_category',
      'atinara_resolution_criteria', eligibility_input ->> 'atinara_resolution_criteria',
      'atinara_resolution_source_url', eligibility_input ->> 'atinara_resolution_source_url',
      'resolution_source_evidence', coalesce(eligibility_input -> 'resolution_source_evidence', '[]'::jsonb),
      'eligibility_status', check_row.status,
      'eligibility_reason_code', check_row.reason_code,
      'eligibility_reason', check_row.reason,
      'eligibility_checked_at', check_row.checked_at,
      'eligibility_expires_at', check_row.expires_at,
      'eligibility_policy_version', check_row.policy_version,
      'eligibility_evidence', check_row.evidence
    )),
    current_eligibility_check_id = check_row.id,
    eligibility_status = check_row.status,
    eligibility_reason_code = check_row.reason_code,
    eligibility_reason = check_row.reason,
    eligibility_evidence = check_row.evidence,
    eligibility_checked_at = check_row.checked_at,
    eligibility_expires_at = check_row.expires_at,
    eligibility_policy_version = check_row.policy_version,
    updated_at = now()
  where candidate_alias.id = candidate.id;

  select * into candidate
  from private.external_market_candidates candidate_alias
  where candidate_alias.id = candidate_id_input;
  safe_payload := private.market_radar_eligibility_payload(candidate);
  if candidate.eligibility_status <> 'eligible' then
    return jsonb_build_object(
      'ok', false,
      'error', case when candidate.eligibility_status = 'terminal'
        then 'RADAR_CANDIDATE_RESOLVED'
        when candidate.eligibility_status = 'duplicate'
        then 'RADAR_CONFIRMED_DUPLICATE'
        else coalesce(candidate.eligibility_reason_code, 'RADAR_CANDIDATE_INELIGIBLE') end,
      'candidate', safe_payload,
      'persisted', true,
      'reservation', jsonb_build_object('preparation_revision', candidate.preparation_revision)
    );
  end if;
  if reserve_for_prepare_input and candidate.state <> 'available' then
    raise exception 'CANDIDATE_NOT_PREPARABLE' using errcode = '40001';
  end if;
  return jsonb_build_object(
    'ok', true,
    'candidate', safe_payload,
    'eligibility_check_id', check_row.id,
    'reservation', jsonb_build_object(
      'preparation_revision', candidate.preparation_revision,
      'idempotent', true
    )
  );
end;
$function$;

