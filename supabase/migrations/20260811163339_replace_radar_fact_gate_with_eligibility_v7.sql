create or replace function public.upsert_market_radar_batch_with_eligibility_v1(
  provider_input text,
  cache_key_input text,
  normalizer_version_input text,
  candidates_input jsonb,
  eligibility_checks_input jsonb,
  eligibility_policy_version_input text,
  provider_status_input jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  item jsonb;
  check_item jsonb;
  item_ordinality bigint;
  candidate private.external_market_candidates%rowtype;
  check_row private.market_radar_eligibility_checks%rowtype;
  accepted_count_value integer := 0;
  quarantined_count_value integer := 0;
  quarantined_value jsonb := '[]'::jsonb;
  returned_state text;
  returned_message text;
  safe_error_code text;
  safe_external_id text;
  safe_fingerprint text;
  check_attempt_id uuid;
  check_checked_at timestamptz;
  check_expires_at timestamptz;
begin
  if auth.role() <> 'service_role' then
    raise exception 'SERVICE_ROLE_REQUIRED' using errcode = '42501';
  end if;
  if provider_input not in ('polymarket', 'kalshi', 'tavily')
     or normalizer_version_input <> 'atinara-radar-v2'
     or eligibility_policy_version_input <> 'atinara-prediction-policy-v5'
     or jsonb_typeof(candidates_input) <> 'array'
     or jsonb_typeof(eligibility_checks_input) <> 'array'
     or jsonb_array_length(candidates_input) <> jsonb_array_length(eligibility_checks_input)
     or jsonb_array_length(candidates_input) > 240
     or octet_length(candidates_input::text) > 3145728 then
    raise exception 'INVALID_RADAR_ELIGIBILITY_BATCH' using errcode = '22023';
  end if;

  for item, item_ordinality in
    select value, ordinality
    from jsonb_array_elements(candidates_input) with ordinality
  loop
    check_item := eligibility_checks_input -> (item_ordinality::integer - 1);
    begin
      candidate := null;
      select * into candidate
      from private.external_market_candidates candidate_alias
      where candidate_alias.provider = provider_input
        and candidate_alias.external_id = item ->> 'external_id'
      for update;

      -- A conclusive terminal decision is monotonic. A later provider refresh
      -- may still report the contract as tradable, but it cannot make a public
      -- result unknown again. Reopening requires an explicit audited repair.
      if found
         and candidate.eligibility_status = 'terminal'
         and item ->> 'eligibility_status' is distinct from 'terminal'
         and jsonb_typeof(check_item) = 'object' then
        item := item || jsonb_build_object(
          'eligibility_status', 'terminal',
          'eligibility_reason_code', candidate.eligibility_reason_code,
          'eligibility_reason', candidate.eligibility_reason,
          'eligibility_evidence', candidate.eligibility_evidence,
          'eligibility_policy_version', 'atinara-prediction-policy-v5'
        );
        check_item := check_item || jsonb_build_object(
          'status', 'terminal',
          'reason_code', candidate.eligibility_reason_code,
          'reason', candidate.eligibility_reason,
          'evidence', candidate.eligibility_evidence,
          'decision_hash', encode(extensions.digest(convert_to(
            concat_ws('|', provider_input, candidate.external_id, 'terminal',
              coalesce(candidate.eligibility_reason_code, ''),
              coalesce(check_item ->> 'checked_at', '')),
            'UTF8'
          ), 'sha256'), 'hex')
        );
      end if;
      if item ->> 'provider' is distinct from provider_input
         or item ->> 'eligibility_policy_version' is distinct from 'atinara-prediction-policy-v5'
         or item ->> 'eligibility_status' not in (
           'eligible', 'terminal', 'inactive_option', 'technical_hold', 'invalid', 'duplicate'
         )
         or jsonb_typeof(check_item) <> 'object'
         or check_item ->> 'provider' is distinct from provider_input
         or check_item ->> 'external_id' is distinct from item ->> 'external_id'
         or check_item ->> 'policy_version' is distinct from 'atinara-prediction-policy-v5'
         or check_item ->> 'status' is distinct from item ->> 'eligibility_status'
         or coalesce(check_item ->> 'decision_hash', '') !~ '^[0-9a-f]{64}$'
         or jsonb_typeof(coalesce(check_item -> 'evidence', '[]'::jsonb)) <> 'array'
         or jsonb_array_length(coalesce(check_item -> 'evidence', '[]'::jsonb)) > 12 then
        raise exception 'INVALID_RADAR_ELIGIBILITY' using errcode = '22023';
      end if;
      begin
        check_attempt_id := (check_item ->> 'attempt_id')::uuid;
        check_checked_at := (check_item ->> 'checked_at')::timestamptz;
        check_expires_at := (check_item ->> 'expires_at')::timestamptz;
      exception when invalid_text_representation or datetime_field_overflow then
        raise exception 'INVALID_RADAR_ELIGIBILITY_DATE' using errcode = '22007';
      end;
      if check_expires_at <= check_checked_at then
        raise exception 'INVALID_RADAR_ELIGIBILITY_DATE' using errcode = '22007';
      end if;

      perform public.upsert_market_radar_batch_v2(
        provider_input,
        left(cache_key_input, 180),
        normalizer_version_input,
        jsonb_build_array(item),
        provider_status_input
      );

      select * into candidate
      from private.external_market_candidates candidate_alias
      where candidate_alias.provider = provider_input
        and candidate_alias.external_id = item ->> 'external_id'
      for update;
      if not found then
        raise exception 'RADAR_ROW_PERSISTENCE_INCOMPLETE' using errcode = 'P0001';
      end if;

      insert into private.market_radar_eligibility_checks (
        attempt_id, candidate_id, provider, external_id, event_group_key,
        policy_version, status, reason_code, reason, evidence,
        checked_at, expires_at, decision_hash
      ) values (
        check_attempt_id,
        candidate.id,
        provider_input,
        candidate.external_id,
        nullif(left(check_item ->> 'event_group_key', 240), ''),
        'atinara-prediction-policy-v5',
        check_item ->> 'status',
        nullif(left(check_item ->> 'reason_code', 100), ''),
        nullif(left(check_item ->> 'reason', 1000), ''),
        coalesce(check_item -> 'evidence', '[]'::jsonb),
        check_checked_at,
        check_expires_at,
        lower(check_item ->> 'decision_hash')
      )
      on conflict (attempt_id) do nothing;

      select * into check_row
      from private.market_radar_eligibility_checks check_alias
      where check_alias.attempt_id = check_attempt_id;
      if not found
         or check_row.candidate_id is distinct from candidate.id
         or check_row.decision_hash is distinct from lower(check_item ->> 'decision_hash') then
        raise exception 'RADAR_ELIGIBILITY_IDEMPOTENCY_CONFLICT' using errcode = '40001';
      end if;

      update private.external_market_candidates candidate_alias set
        current_eligibility_check_id = check_row.id,
        eligibility_status = check_row.status,
        eligibility_reason_code = check_row.reason_code,
        eligibility_reason = check_row.reason,
        eligibility_evidence = check_row.evidence,
        eligibility_checked_at = check_row.checked_at,
        eligibility_expires_at = check_row.expires_at,
        eligibility_policy_version = check_row.policy_version,
        updated_at = now()
      where candidate_alias.id = candidate.id;
      accepted_count_value := accepted_count_value + 1;
    exception when others then
      get stacked diagnostics
        returned_state = returned_sqlstate,
        returned_message = message_text;
      if returned_state = '57014'
         or not (
           returned_message in (
             'INVALID_RADAR_CANDIDATE',
             'INCOMPLETE_RADAR_VERIFICATION',
             'RADAR_BATCH_TOO_LARGE',
             'INVALID_RADAR_ELIGIBILITY',
             'INVALID_RADAR_ELIGIBILITY_DATE'
           )
           or returned_state in (
             '22001', '22003', '22007', '22008', '22P02',
             '23502', '23503', '23514'
           )
         ) then
        raise;
      end if;
      safe_error_code := case when returned_message in (
        'INVALID_RADAR_CANDIDATE', 'INCOMPLETE_RADAR_VERIFICATION',
        'RADAR_BATCH_TOO_LARGE', 'INVALID_RADAR_ELIGIBILITY',
        'INVALID_RADAR_ELIGIBILITY_DATE'
      ) then returned_message else 'RADAR_CANDIDATE_DATA_INVALID' end;
      safe_external_id := coalesce(nullif(left(item ->> 'external_id', 220), ''), '[sin-identificador]');
      safe_fingerprint := case when coalesce(item ->> 'fingerprint', '') ~ '^[0-9a-fA-F]{64}$'
        then lower(item ->> 'fingerprint') else null end;
      insert into private.market_radar_candidate_quarantines(
        provider, cache_key, external_id, fingerprint, stage,
        error_code, database_code, operation
      ) values (
        provider_input, left(cache_key_input, 180), safe_external_id,
        safe_fingerprint, 'eligibility_persistence', safe_error_code,
        returned_state, 'upsert_market_radar_batch_with_eligibility_v1'
      );
      quarantined_count_value := quarantined_count_value + 1;
      quarantined_value := quarantined_value || jsonb_build_array(jsonb_build_object(
        'provider', provider_input,
        'external_id', safe_external_id,
        'fingerprint', safe_fingerprint,
        'stage', 'eligibility_persistence',
        'code', safe_error_code,
        'database_code', returned_state,
        'operation', 'upsert_market_radar_batch_with_eligibility_v1'
      ));
    end;
  end loop;

  return jsonb_build_object(
    'ok', true,
    'upserted', accepted_count_value,
    'accepted_count', accepted_count_value,
    'eligibility_checks_linked', accepted_count_value,
    'quarantined_count', quarantined_count_value,
    'quarantined', quarantined_value,
    'row_isolation', 'database_subtransaction_v1',
    'atomic_per_candidate', true
  );
end;
$function$;

