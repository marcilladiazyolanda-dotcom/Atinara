create or replace function private.assert_market_radar_draft_eligibility_v1(
  draft_input private.market_drafts,
  checked_at_input timestamptz default clock_timestamp()
)
returns void
language plpgsql
security definer
set search_path = ''
as $function$
declare
  candidate private.external_market_candidates%rowtype;
  eligibility private.market_radar_eligibility_checks%rowtype;
  provenance jsonb := coalesce(draft_input.source_provenance, '{}'::jsonb);
  provenance_check_id bigint;
  provenance_revision bigint;
begin
  if draft_input.radar_candidate_id is null
     and not (provenance ? 'radar_candidate_id')
     and not (provenance ? 'radar_eligibility_check_id')
     and not (provenance ? 'radar_fact_check_id') then
    return;
  end if;
  if draft_input.radar_candidate_id is null then
    raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
  end if;
  select * into candidate
  from private.external_market_candidates candidate_alias
  where candidate_alias.id = draft_input.radar_candidate_id
  for share;
  if not found then
    raise exception 'RADAR_ELIGIBILITY_REQUIRED' using errcode = '55000';
  end if;
  if checked_at_input is null
     or checked_at_input > clock_timestamp() + interval '1 minute' then
    raise exception 'RADAR_ELIGIBILITY_CHECK_TIME_INVALID' using errcode = '22007';
  end if;
  if coalesce(provenance ->> 'radar_preparation_revision', '') !~ '^[1-9][0-9]*$' then
    raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
  end if;
  begin
    provenance_revision := (provenance ->> 'radar_preparation_revision')::bigint;
  exception when invalid_text_representation or numeric_value_out_of_range then
    raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
  end;
  -- A renewed check may rotate from A to B while the material projection stays
  -- at R. Any material refresh to R+1 invalidates the draft and its review.
  perform private.assert_market_radar_candidate_eligible_v1(
    candidate.id, provenance_revision
  );

  if provenance ? 'radar_eligibility_check_id' then
    begin
      provenance_check_id := (provenance ->> 'radar_eligibility_check_id')::bigint;
    exception when invalid_text_representation or numeric_value_out_of_range then
      raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
    end;
    select * into eligibility
    from private.market_radar_eligibility_checks check_alias
    where check_alias.id = provenance_check_id;
    if not found
       or eligibility.candidate_id is distinct from candidate.id
       or eligibility.policy_version is distinct from provenance ->> 'radar_eligibility_policy_version'
       or eligibility.status is distinct from 'eligible'
       or eligibility.decision_hash is distinct from provenance ->> 'radar_eligibility_decision_hash' then
      raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
    end if;
  elsif not (provenance ? 'radar_fact_check_id') then
    -- Only historical Radar drafts may use the legacy append-only provenance.
    raise exception 'RADAR_DRAFT_ELIGIBILITY_PROVENANCE_REQUIRED' using errcode = '55000';
  end if;
end;
$function$;

