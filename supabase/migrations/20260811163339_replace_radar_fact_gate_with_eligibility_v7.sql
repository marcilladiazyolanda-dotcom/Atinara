create or replace function public.record_market_radar_eligibility_attempt_v1(
  candidate_id_input uuid,
  expected_preparation_revision_input bigint,
  purpose_input text,
  attempt_id_input uuid,
  phase_input text,
  error_code_input text,
  retryable_input boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  candidate private.external_market_candidates%rowtype;
  attempt private.market_radar_eligibility_attempts%rowtype;
begin
  if auth.role() <> 'service_role' then
    raise exception 'SERVICE_ROLE_REQUIRED' using errcode = '42501';
  end if;
  if attempt_id_input is null
     or purpose_input not in ('prepare', 'revalidate')
     or phase_input not in ('provider_revalidation', 'official_terminal_scan', 'eligibility_persistence')
     or coalesce(error_code_input, '') !~ '^[A-Z][A-Z0-9_]{2,100}$' then
    raise exception 'INVALID_RADAR_ELIGIBILITY_ATTEMPT' using errcode = '22023';
  end if;

  select * into candidate
  from private.external_market_candidates candidate_alias
  where candidate_alias.id = candidate_id_input
  for share;
  if not found then raise exception 'RADAR_CANDIDATE_NOT_FOUND' using errcode = 'P0001'; end if;
  if candidate.preparation_revision is distinct from expected_preparation_revision_input then
    raise exception 'PREPARATION_REVISION_MISMATCH' using errcode = '40001';
  end if;

  insert into private.market_radar_eligibility_attempts(
    attempt_id, candidate_id, preparation_revision, purpose, phase,
    error_code, retryable, state_preserved
  ) values (
    attempt_id_input, candidate.id, candidate.preparation_revision, purpose_input,
    phase_input, error_code_input, coalesce(retryable_input, false), true
  ) on conflict (attempt_id) do nothing;

  select * into attempt
  from private.market_radar_eligibility_attempts attempt_alias
  where attempt_alias.attempt_id = attempt_id_input;
  if not found
     or attempt.candidate_id is distinct from candidate.id
     or attempt.preparation_revision is distinct from candidate.preparation_revision
     or attempt.purpose is distinct from purpose_input
     or attempt.phase is distinct from phase_input
     or attempt.error_code is distinct from error_code_input then
    raise exception 'RADAR_ELIGIBILITY_ATTEMPT_CONFLICT' using errcode = '40001';
  end if;

  return jsonb_build_object(
    'ok', true,
    'attempt_id', attempt.attempt_id,
    'attempt_record_id', attempt.id,
    'state_preserved', true,
    'authoritative_pointer_unchanged', true,
    'preparation_revision', candidate.preparation_revision,
    'idempotent', true
  );
end;
$function$;

