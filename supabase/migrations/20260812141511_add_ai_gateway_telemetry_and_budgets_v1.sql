create or replace function private.reserve_ai_provider_budget_private_v1(
  invocation_id_input text,
  provider_id_input text,
  task_type_input text,
  requested_units_input bigint,
  budget_mode_input text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $function$
declare
  invocation_value text := trim(coalesce(invocation_id_input, ''));
  provider_value text := trim(coalesce(provider_id_input, ''));
  task_value text := trim(coalesce(task_type_input, ''));
  mode_value text := trim(coalesce(budget_mode_input, ''));
  day_value date := (clock_timestamp() at time zone 'UTC')::date;
  previous private.ai_provider_budget_reservations%rowtype;
  limit_value bigint;
  used_value bigint;
  status_value text;
begin
  if invocation_value !~ '^[A-Za-z0-9._:-]{1,120}$'
     or provider_value not in ('gemini', 'openrouter', 'nvidia_nim')
     or task_value not in (
       'radar_candidate_enrichment', 'market_draft_validation', 'market_expert_reasoning',
       'market_draft_repair', 'market_resolution_analysis'
     )
     or requested_units_input is null or requested_units_input < 1
     or mode_value not in ('baseline_existing', 'metered') then
    raise exception 'AI_BUDGET_INVALID_REQUEST' using errcode = '22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(provider_value || ':' || task_value || ':' || day_value::text, 0)
  );

  select * into previous
  from private.ai_provider_budget_reservations reservation
  where reservation.invocation_id = invocation_value
    and reservation.provider_id = provider_value
    and reservation.task_type = task_value
    and reservation.budget_day = day_value;

  if found then
    if previous.requested_units <> requested_units_input or previous.budget_mode <> mode_value then
      raise exception 'AI_BUDGET_IDEMPOTENCY_CONFLICT' using errcode = '23505';
    end if;
    return jsonb_build_object(
      'status', previous.status,
      'reserved', previous.status = 'reserved',
      'idempotent', true,
      'requested_units', previous.requested_units,
      'used_units', previous.used_units,
      'limit_units', previous.limit_units
    );
  end if;

  if mode_value = 'baseline_existing' then
    insert into private.ai_provider_budget_reservations (
      invocation_id, provider_id, task_type, budget_day, requested_units,
      budget_mode, status, used_units, limit_units
    ) values (
      invocation_value, provider_value, task_value, day_value, requested_units_input,
      mode_value, 'reserved', null, null
    );
    return jsonb_build_object(
      'status', 'reserved', 'reserved', true, 'idempotent', false,
      'requested_units', requested_units_input, 'used_units', null, 'limit_units', null
    );
  end if;

  select coalesce(limit_row.daily_limit_units, 0)
    into limit_value
  from private.ai_provider_budget_limits limit_row
  where limit_row.provider_id = provider_value
    and limit_row.task_type = task_value
    and limit_row.active
  for share;
  limit_value := coalesce(limit_value, 0);

  insert into private.ai_provider_budget_days (
    provider_id, task_type, budget_day, limit_units, used_units
  ) values (
    provider_value, task_value, day_value, limit_value, 0
  ) on conflict (provider_id, task_type, budget_day) do nothing;

  update private.ai_provider_budget_days budget_day
  set used_units = budget_day.used_units + requested_units_input
  where budget_day.provider_id = provider_value
    and budget_day.task_type = task_value
    and budget_day.budget_day = day_value
    and budget_day.used_units + requested_units_input <= budget_day.limit_units
  returning budget_day.used_units, budget_day.limit_units into used_value, limit_value;

  if found then
    status_value := 'reserved';
  else
    status_value := 'exhausted';
    select budget_day.used_units, budget_day.limit_units
      into used_value, limit_value
    from private.ai_provider_budget_days budget_day
    where budget_day.provider_id = provider_value
      and budget_day.task_type = task_value
      and budget_day.budget_day = day_value;
  end if;

  insert into private.ai_provider_budget_reservations (
    invocation_id, provider_id, task_type, budget_day, requested_units,
    budget_mode, status, used_units, limit_units
  ) values (
    invocation_value, provider_value, task_value, day_value, requested_units_input,
    mode_value, status_value, used_value, limit_value
  );

  return jsonb_build_object(
    'status', status_value,
    'reserved', status_value = 'reserved',
    'idempotent', false,
    'requested_units', requested_units_input,
    'used_units', used_value,
    'limit_units', limit_value
  );
end;
$function$;

