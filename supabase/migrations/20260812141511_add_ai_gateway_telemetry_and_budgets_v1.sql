create table private.ai_task_runtime_settings (
  task_type text primary key,
  contract_version text not null,
  policy_version text not null,
  transport_mode text not null default 'legacy_direct',
  primary_route_id text,
  fallback_route_id text,
  openrouter_enabled boolean not null default false,
  nvidia_nim_enabled boolean not null default false,
  updated_at timestamptz not null default now(),
  constraint ai_task_runtime_task_check check (task_type in (
    'radar_candidate_enrichment',
    'market_draft_validation',
    'market_expert_reasoning',
    'market_draft_repair',
    'market_resolution_analysis'
  )),
  constraint ai_task_runtime_mode_check check (transport_mode in (
    'legacy_direct', 'gateway_gemini_parity', 'gateway_routing'
  )),
  constraint ai_task_runtime_route_check check (
    transport_mode <> 'gateway_routing' or primary_route_id is not null
  ),
  constraint ai_task_runtime_experimental_check check (
    transport_mode = 'gateway_routing' or (not openrouter_enabled and not nvidia_nim_enabled)
  )
);

create table private.ai_provider_budget_limits (
  provider_id text not null,
  task_type text not null,
  daily_limit_units bigint not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (provider_id, task_type),
  constraint ai_provider_budget_limits_provider_check check (provider_id in ('gemini', 'openrouter', 'nvidia_nim')),
  constraint ai_provider_budget_limits_task_check check (task_type in (
    'radar_candidate_enrichment',
    'market_draft_validation',
    'market_expert_reasoning',
    'market_draft_repair',
    'market_resolution_analysis'
  )),
  constraint ai_provider_budget_limits_nonnegative_check check (daily_limit_units >= 0)
);

create table private.ai_provider_budget_days (
  provider_id text not null,
  task_type text not null,
  budget_day date not null,
  limit_units bigint not null,
  used_units bigint not null default 0,
  created_at timestamptz not null default now(),
  primary key (provider_id, task_type, budget_day),
  constraint ai_provider_budget_days_nonnegative_check check (
    limit_units >= 0 and used_units >= 0 and used_units <= limit_units
  )
);

create table private.ai_provider_budget_reservations (
  invocation_id text not null,
  provider_id text not null,
  task_type text not null,
  budget_day date not null,
  requested_units bigint not null,
  budget_mode text not null,
  status text not null,
  used_units bigint,
  limit_units bigint,
  created_at timestamptz not null default now(),
  primary key (invocation_id, provider_id, task_type, budget_day),
  constraint ai_budget_reservation_invocation_check check (
    char_length(invocation_id) between 1 and 120 and invocation_id ~ '^[A-Za-z0-9._:-]+$'
  ),
  constraint ai_budget_reservation_requested_check check (requested_units > 0),
  constraint ai_budget_reservation_mode_check check (budget_mode in ('baseline_existing', 'metered')),
  constraint ai_budget_reservation_status_check check (status in ('reserved', 'exhausted')),
  constraint ai_budget_reservation_result_check check (
    (status = 'reserved' and (budget_mode = 'baseline_existing' or used_units is not null))
    or (status = 'exhausted' and used_units is not null and limit_units is not null)
  )
);

create index ai_provider_budget_reservations_created_idx
