create or replace function private.record_ai_invocation_attempt_private_v1(payload_input jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $function$
declare
  existing private.ai_invocation_attempts%rowtype;
  inserted_id bigint;
  invocation_value text := trim(coalesce(payload_input ->> 'invocation_id', ''));
  route_value text := trim(coalesce(payload_input ->> 'route_id', ''));
begin
  if jsonb_typeof(payload_input) <> 'object'
     or invocation_value !~ '^[A-Za-z0-9._:-]{1,120}$'
     or route_value = '' then
    raise exception 'AI_TELEMETRY_INVALID_REQUEST' using errcode = '22023';
  end if;

  select * into existing
  from private.ai_invocation_attempts attempt
  where attempt.invocation_id = invocation_value and attempt.route_id = route_value;
  if found then
    if existing.input_fingerprint <> payload_input ->> 'input_fingerprint'
       or existing.output_fingerprint is distinct from nullif(payload_input ->> 'output_fingerprint', '')
       or existing.outcome <> payload_input ->> 'outcome' then
      raise exception 'AI_TELEMETRY_IDEMPOTENCY_CONFLICT' using errcode = '23505';
    end if;
    return jsonb_build_object('id', existing.id, 'idempotent', true);
  end if;

  insert into private.ai_invocation_attempts (
    invocation_id, agent_run_id, task_type, contract_version, policy_version,
    transport_mode, route_id, provider_id, model_id, data_class,
    input_fingerprint, output_fingerprint, lifecycle, outcome, error_code,
    retry_count, response_bytes, duration_ms, input_tokens, output_tokens,
    provider_request_id, schema_fallback, metrics_eligible
  ) values (
    invocation_value,
    nullif(payload_input ->> 'agent_run_id', ''),
    payload_input ->> 'task_type',
    payload_input ->> 'contract_version',
    payload_input ->> 'policy_version',
    payload_input ->> 'transport_mode',
    route_value,
    payload_input ->> 'provider_id',
    nullif(payload_input ->> 'model_id', ''),
    payload_input ->> 'data_class',
    payload_input ->> 'input_fingerprint',
    nullif(payload_input ->> 'output_fingerprint', ''),
    coalesce(payload_input -> 'lifecycle', '[]'::jsonb),
    payload_input ->> 'outcome',
    nullif(payload_input ->> 'error_code', ''),
    coalesce((payload_input ->> 'retry_count')::integer, 0),
    coalesce((payload_input ->> 'response_bytes')::integer, 0),
    coalesce((payload_input ->> 'duration_ms')::integer, 0),
    (payload_input ->> 'input_tokens')::integer,
    (payload_input ->> 'output_tokens')::integer,
    nullif(left(payload_input ->> 'provider_request_id', 160), ''),
    coalesce((payload_input ->> 'schema_fallback')::boolean, false),
    coalesce((payload_input ->> 'metrics_eligible')::boolean, false)
  ) returning id into inserted_id;
  return jsonb_build_object('id', inserted_id, 'idempotent', false);
end;
$function$;

